"""Нормализация названий регионов/городов ПВЗ для группировки в отчетах.

DaData пишет одно и то же по-разному («Московская область» / «Московская обл»,
«Москва» / «г Москва», «Респ Татарстан» / «Республика Татарстан») — без
нормализации дубли группируются раздельно.
Нормы хранятся в pvz_all.region_norm / city_norm (заполняет scripts/pvz_norm.py),
отчеты группируют по готовым колонкам и никакой строковой хирургии в SQL не делают.

Каноника = полные официальные названия (как большинство DaData и как боевой
$regionFixes/getInternalMapping в wbcms/commands/AddressController.php):
«Республика Татарстан», «Ханты-Мансийский автономный округ», «Москва».

Два уровня правок (порядок важен!):
  1. REGION_OVERRIDES / CITY_OVERRIDES ниже — точные совпадения для уродцев
     («Еврейская Аобл», «Кемеровская область - Кузбасс», ...).
     ДОПОЛНЯЙТЕ СЮДА новые случаи, затем scripts/pvz_norm.py --all.
  2. normalize_region / normalize_city — общая алгоритмика для остальных.
"""


