def normalize_region(s: str | None) -> str | None:
    """'Московская обл' -> 'Московская область', 'респ Татарстан' -> 'Республика Татарстан'."""
    s = (s or "").strip()
    if not s:
        return None
    if s in REGION_OVERRIDES:
        return REGION_OVERRIDES[s]
    low = s.lower()
    for pref in ("республика ", "респ. ", "респ "):
        if low.startswith(pref):
            s = "Республика " + s[len(pref):].strip()
            break
    # суффикс: «Удмуртская респ» -> «Удмуртская Республика»
    low = s.lower()
    for suf in (" респ.", " респ"):
        if low.endswith(suf):
            s = s[: -len(suf)] + " Республика"
            break
    # суффикс-сокращение: «Еврейская а.обл.» -> «Еврейская автономная область»,
    # «Ямало-Ненецкий а.окр.» -> «Ямало-Ненецкий автономный округ»
    low = s.lower()
    for suf, full in ((" а.обл.", " автономная область"), (" а.обл", " автономная область"),
                      (" а.окр.", " автономный округ"), (" а.окр", " автономный округ")):
        if low.endswith(suf):
            s = s[: -len(suf)] + full
            break
    while s.startswith("г "):
        s = s[2:]
    if s.endswith(" обл"):
        s = s[: -len(" обл")] + " область"
    s = s.strip()
    return s or None


def normalize_city(s: str | None) -> str | None:
    """'г Москва' -> 'Москва'."""
    s = (s or "").strip()
    if not s:
        return None
    if s in CITY_OVERRIDES:
        return CITY_OVERRIDES[s]
    while s.startswith("г "):
        s = s[2:]
    s = s.strip()
    return s or None


def normalize_country(s: str | None) -> str | None:
    """Код страны в нижний регистр ('RU' -> 'ru'): сравнение идет прямым
    равенством под idx_pvz_country, без UPPER/IN-костылей."""
    s = (s or "").strip().lower()
    return s or None


