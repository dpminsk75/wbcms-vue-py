"""Имена операций WB (supplier_oper_name) — единый источник правды.

WB периодически переименовывает операции в отчёте `sales-reports/detailed`.
Факт (проверено на боевой БД, 2026-10-26):

| период | операция            | строк | delivery_rub       |
|--------|--------------------|-------|-------------------|
| 2026-07 | «Логистика»       | 5355  | 252 648,20         |
| 2026-08 | «Логистика»       | 4810  | 220 893,81         |
| 2026-08 | «Доставка»        | 8     | 299,64             |  ← переименование ~8 августа 2026
| 2026-09 | «Доставка»        | 754   | 32 094,19          |

Переименование **не обратное**: старые строки в `detail_by_period` остаются с
именем «Логистика», новые приходят как «Доставка». Поэтому фильтр по операции
доставки ВСЕГДА должен быть `IN (...)`, а не `= '...'`.

Аналогично переименовываются и `bonus_type_name`:
  «От клиента при отмене» (июль–сентябрь) → «От клиенту при отмене» (октябрь+).
Поэтому разбивка отчёта по причинам строится на ШАБЛОНАХ (LIKE), а не на
точных названиях — см. `backend/services/penalty_service.py`.

Список операций за сентябрь 2026 (DISTINCT supplier_oper_name):
  Возврат, Возмещение за выдачу и возврат товаров на ПВЗ,
  Возмещение издержек по перемещению и операционной обработке товара,
  Доставка, Компенсация скидки по программе лояльности, Продажа,
  Стоимость участия в программе лояльности,
  Сумма баллов, удержанных в рамках акции "Баллы за отзывы",
  Сумма баллов, удержанных за покупку товаров, Удержание,
  Услуга по обработке Товара, Хранение, Штраф.
"""

# Операции «доставка/логистика» — по ним считаем факты выкупа и отчёт по потерям.
# «Коррекция стоимости доставки» — корректировка доставки (отдельная операция WB),
# по смыслу это тоже доставка, включаем в срез (решение владельца, 2026-10-26).
LOGISTICS_OPS: tuple[str, ...] = (
    "Логистика",
    "Доставка",
    "Коррекция стоимости доставки",
)

# Операция «Штраф» — штрафы WB за нарушения продавца (отдельно от потерь на доставке).
PENALTY_OP = "Штраф"

# Операции продажи/возврата — не переименовывались, но держим здесь для единообразия.
SALE_OP = "Продажа"
RETURN_OP = "Возврат"

# Шаблоны bonus_type_name для разбивки потерь на доставке.
# Названия WB меняются («От клиента при отмене» → «От клиенту при отмене»),
# поэтому матчим по смыслу, а не по строке.
#
# Разбивка как в Yii2 (WbPenaltyController::getProductSummary) — 5 корзин:
#   «Отмена (->)» — логистика К клиенту при отмене
#   «Отмена (<-)» — логистика ОБРАТНО (клиент отменил)
#   «Возврат (<-)» — возврат товара клиентом
#   «Брак»        — «Возврат брака (К продавцу)»
#   «Прочее»      — всё остальное
# Порядок важен: сначала специфичные, потом брак, потом остальное.
REASON_TO_CLIENT_CANCEL = "К клиенту при отмене%"
REASON_FROM_CLIENT_CANCEL = "От клиент% при отмене%"
REASON_FROM_CLIENT_RETURN = "От клиент% при возврате%"
REASON_DEFECT = "%брак%"

# Сводные категории (для группировки причин в отчёте)
REASON_CANCEL = "%отмен%"
REASON_RETURN = "%возврат%"

# Штатная доставка — не потеря, исключаем из отчёта (как в Yii2).
REASON_DELIVERY_PLAIN = "К клиенту при продаже"


def ops_sql(ops: tuple[str, ...] = LOGISTICS_OPS) -> str:
    """Готовая SQL-строка для IN (...) по именам операций.

    Значения подставляются литералами (с экранированием кавычек) — список
    операций зашит в коде, пользовательских данных там нет.
    """
    if not ops:
        return "(NULL)"
    parts = []
    for o in ops:
        parts.append("'" + str(o).replace("\\", "\\\\").replace("'", "''") + "'")
    return "(" + ", ".join(parts) + ")"
