"""Экранирование пользовательской маски для LIKE.

Маска из поля «Товар» — произвольная строка: артикул может содержать `_`
(«ДС_СВ_Амигуруми_25$»), а в LIKE `_` — любой символ, `%` — любую
последовательность. Без экранирования поиск по маске находит лишние
карточки, и подсказки фильтра расходятся с самим фильтром.

ESCAPE-символ — обратный слэш: в SQL-литерале это '\\\\' (MySQL видит '\\').
"""


def escape_like(mask: str) -> str:
    """Экранирует спецсимволы LIKE (\\, %, _) в пользовательской маске."""
    return (str(mask)
            .replace("\\", "\\\\")
            .replace("%", "\\%")
            .replace("_", "\\_"))
